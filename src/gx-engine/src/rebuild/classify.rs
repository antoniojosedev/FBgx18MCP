//! Phase 0: sorts catalog objects into what is built, skipped, refused or only counted.

use super::SkippedObject;
use crate::{
    catalog::{Catalog, KbObject, ObjectId, ObjectKind},
    csharp::{
        ProcedureClass,
        webform::{self, WebClass, WebPanelEnvironment},
    },
};
use std::{
    collections::{BTreeMap, BTreeSet},
    time::Instant,
};

/// Categorized catalog objects.
#[derive(Default)]
pub(super) struct ObjectManifest<'a> {
    pub procedures: Vec<&'a KbObject>,
    /// Transactions are not compile units; they stay listed so their formulas are verified.
    pub transactions: Vec<&'a KbObject>,
    pub sdts: Vec<&'a KbObject>,
    pub skipped: Vec<SkippedObject>,
    pub not_generated: Vec<SkippedObject>,
    pub not_targeted: Vec<SkippedObject>,
    pub refused: Vec<SkippedObject>,
    pub definitions: BTreeMap<String, usize>,
    pub total_objects: usize,
    /// WebPanels the plain emitter planned: one class each (see `csharp::webform`).
    pub webpanels: Vec<WebClass>,
    /// The values class of each enumerated Domain of the model, as (file name, text) (see `csharp::domain`).
    pub domain_files: Vec<(String, String)>,
}

/// An object of the catalog by name and kind, with the given reason it is not built.
fn skipped_because(obj: &KbObject, reason: impl Into<String>) -> SkippedObject {
    SkippedObject {
        name: obj.name.clone(),
        kind: format!("{:?}", obj.kind),
        reason: reason.into(),
    }
}

/// A web UI or not-generated object, by name and kind, with the reason it is not built.
fn skipped(obj: &KbObject) -> SkippedObject {
    skipped_because(obj, obj.kind.not_compile_unit_reason().unwrap_or_default())
}

pub(super) fn classify_objects<'a>(
    catalog: &'a Catalog,
    web_environment: &WebPanelEnvironment,
    runtime_sdts: &BTreeSet<String>,
) -> (ObjectManifest<'a>, u64) {
    let read_start = Instant::now();
    let mut manifest = ObjectManifest::default();
    let targeted = crate::reachability::targeted_objects(catalog);

    for obj in catalog.objects() {
        manifest.total_objects += 1;
        if let Some(reason) = not_targeted_reason(obj, &targeted, runtime_sdts) {
            manifest.not_targeted.push(skipped_because(obj, reason));
            continue;
        }
        // An object the reader refused is never emitted empty: it is an error, named, and counts as
        // refused. Its dependants are refused by the dependency walk below.
        if let Some(reason) = &obj.refusal {
            manifest.refused.push(skipped_because(
                obj,
                format!("refused by the reader: {reason}"),
            ));
            continue;
        }
        // A stored not-generated object (a Procedure the SDK does not generate) is skipped by name, and
        // is neither emitted nor an error. A caller that needs it is refused in the walk below.
        if let Some(reason) = &obj.not_generated {
            manifest
                .skipped
                .push(skipped_because(obj, format!("not generated: {reason}")));
            continue;
        }
        classify_by_kind(&mut manifest, obj, catalog, web_environment);
    }

    refuse_unbuildable_dependents(&mut manifest, catalog);

    let read_ms = read_start.elapsed().as_millis() as u64;
    (manifest, read_ms)
}

/// Why an object is not built although nothing refuses it, or `None` when it is built.
///
/// A structured data type no generated object reaches is not built, and is not refused even when this
/// engine cannot decode it (see `crate::reachability`). A library one the runtime assemblies define is not
/// built even when reached: the generated code uses the runtime class. A Procedure stored as not main that
/// no generated object reaches is not generated by the SDK (spc0217), so it is not built here either.
fn not_targeted_reason(
    obj: &KbObject,
    targeted: &BTreeSet<ObjectId>,
    runtime_sdts: &BTreeSet<String>,
) -> Option<&'static str> {
    match obj.kind {
        ObjectKind::StructuredDataType if !targeted.contains(&obj.id) => Some(if obj.library {
            crate::reachability::LIBRARY_NOT_TARGETED_REASON
        } else {
            crate::reachability::UNREACHED_SDT_REASON
        }),
        ObjectKind::StructuredDataType if obj.library && runtime_sdts.contains(&obj.name) => {
            Some(crate::reachability::RUNTIME_PROVIDED_REASON)
        }
        ObjectKind::Procedure if obj.main == Some(false) && !targeted.contains(&obj.id) => {
            Some(crate::reachability::UNREACHABLE_REASON)
        }
        _ => None,
    }
}

fn classify_by_kind<'a>(
    manifest: &mut ObjectManifest<'a>,
    obj: &'a KbObject,
    catalog: &Catalog,
    web_environment: &WebPanelEnvironment,
) {
    match obj.kind {
        ObjectKind::Procedure => manifest.procedures.push(obj),
        ObjectKind::StructuredDataType => manifest.sdts.push(obj),
        ObjectKind::Transaction => classify_transaction(manifest, obj, catalog, web_environment),
        ObjectKind::WebPanel => match webform::plan_web_class(obj, catalog, web_environment) {
            Ok(plan) => manifest.webpanels.push(plan),
            Err(reason) => manifest.skipped.push(skipped_because(
                obj,
                format!("web UI, not generated: {reason}"),
            )),
        },
        ObjectKind::DataProvider => match ProcedureClass::from_kb_object(obj) {
            Ok(_) => manifest.procedures.push(obj),
            Err(reason) => manifest.not_generated.push(skipped_because(obj, reason)),
        },
        ObjectKind::DataSelector | ObjectKind::DataView => {
            manifest.not_generated.push(skipped(obj));
        }
        _ => classify_definition(manifest, obj),
    }
}

/// A Transaction is listed for formula verification and is emitted with the web classes when its form is a
/// matched shape (`transaction_form`, then Work With); any other is skipped by name.
fn classify_transaction<'a>(
    manifest: &mut ObjectManifest<'a>,
    obj: &'a KbObject,
    catalog: &Catalog,
    web_environment: &WebPanelEnvironment,
) {
    manifest.transactions.push(obj);
    match crate::csharp::transaction_form::plan_transaction_form(obj, catalog, web_environment) {
        Ok(plan) => manifest.webpanels.push(WebClass::Transaction(plan)),
        Err(reason) => {
            match crate::csharp::work_with::plan_work_with(obj, catalog, web_environment) {
                Ok(plan) => manifest.webpanels.push(WebClass::WorkWith(plan)),
                Err(work_with) => manifest.skipped.push(skipped_because(
                    obj,
                    format!(
                        "web UI, not generated: {reason}; as a Work With Transaction: {work_with}"
                    ),
                )),
            }
        }
    }
}

/// An object with no compile unit by nature (Module, Domain, Attribute, ...), counted by kind.
fn classify_definition(manifest: &mut ObjectManifest<'_>, obj: &KbObject) {
    // An enumerated Domain of the model has a values class; one whose stored shape the
    // emitter does not cover is skipped by name, never written in a guessed shape.
    if obj.kind == ObjectKind::Domain {
        match crate::csharp::domain::enum_domain_file(obj) {
            Some(Ok(file)) => manifest.domain_files.push(file),
            Some(Err(reason)) => manifest.skipped.push(skipped_because(
                obj,
                format!("values class not generated: {reason}"),
            )),
            None => {}
        }
    }
    *manifest
        .definitions
        .entry(format!("{:?}", obj.kind))
        .or_default() += 1;
}

/// A Procedure or SDT that needs a web UI or not-generated object is refused, never built. It leaves the
/// buildable set; `rebuild_all` reports it as an error. An SDT whose structure uses a refused or
/// unbuildable object is refused by the same rule: its class would name a type that is never generated,
/// so it is an error, not a class that does not compile.
fn refuse_unbuildable_dependents(manifest: &mut ObjectManifest<'_>, catalog: &Catalog) {
    let procedures = std::mem::take(&mut manifest.procedures);
    manifest.procedures = keep_buildable(catalog, procedures, "Procedure", &mut manifest.refused);
    let sdts = std::mem::take(&mut manifest.sdts);
    manifest.sdts = keep_buildable(catalog, sdts, "StructuredDataType", &mut manifest.refused);
}

/// `objects` without those that need an unbuildable object; each of those is added to `refused` under
/// `kind`, which is the kind the report names (a DataProvider is built, and refused, as a Procedure).
fn keep_buildable<'a>(
    catalog: &Catalog,
    objects: Vec<&'a KbObject>,
    kind: &str,
    refused: &mut Vec<SkippedObject>,
) -> Vec<&'a KbObject> {
    let mut buildable = Vec::with_capacity(objects.len());
    for object in objects {
        match first_unbuildable_dependency(catalog, object) {
            Some(dependency) => refused.push(SkippedObject {
                name: object.name.clone(),
                kind: kind.into(),
                reason: blocker_reason(&dependency),
            }),
            None => buildable.push(object),
        }
    }
    buildable
}

/// Why a dependency cannot be built: the reader's refusal, or the reason its kind is not a compile unit.
fn unbuildable_reason(object: &KbObject) -> String {
    match (&object.refusal, &object.not_generated) {
        (Some(reason), _) => format!("refused by the reader: {reason}"),
        (None, Some(reason)) => format!("not generated: {reason}"),
        (None, None) => object
            .kind
            .not_compile_unit_reason()
            .unwrap_or_default()
            .to_string(),
    }
}

/// What stops a dependency from being built: a web UI or not-generated object, or a reference target
/// the catalog does not hold.
enum Blocker<'a> {
    Object(&'a KbObject),
    Missing(ObjectId),
}

/// The refusal reason of a blocked dependency, in the words the report carries.
fn blocker_reason(blocker: &Blocker<'_>) -> String {
    match blocker {
        Blocker::Object(object) => format!(
            "needs {:?} '{}' ({})",
            object.kind,
            object.name,
            unbuildable_reason(object)
        ),
        Blocker::Missing(id) => format!(
            "needs '{}', which is not in the catalog (refused: every reference target must be present)",
            id.as_str()
        ),
    }
}

/// The first web UI or not-generated object that a Procedure needs, directly or through its
/// dependency chain, or the first reference target the catalog does not hold. Such an object is
/// terminal: it is not a compile unit, so the walk does not continue past it. The root module emits
/// nothing and every object refers to it, so its absence is not a blocker.
fn first_unbuildable_dependency<'a>(
    catalog: &'a Catalog,
    procedure: &KbObject,
) -> Option<Blocker<'a>> {
    let mut seen: BTreeSet<ObjectId> = BTreeSet::new();
    let mut pending: Vec<ObjectId> = procedure
        .references
        .iter()
        .map(|reference| reference.target.clone())
        .collect();
    while let Some(id) = pending.pop() {
        if !seen.insert(id.clone()) {
            continue;
        }
        let Some(object) = catalog.get(&id) else {
            if id.as_str() == crate::udm::reader::SYSTEM_ROOT_OBJECT_ID {
                continue;
            }
            return Some(Blocker::Missing(id));
        };
        if object.refusal.is_some()
            || object.not_generated.is_some()
            || (object.kind.not_compile_unit_reason().is_some()
                && !(object.kind == ObjectKind::DataProvider
                    && ProcedureClass::from_kb_object(object).is_ok()))
        {
            return Some(Blocker::Object(object));
        }
        pending.extend(
            object
                .references
                .iter()
                .map(|reference| reference.target.clone()),
        );
    }
    None
}
